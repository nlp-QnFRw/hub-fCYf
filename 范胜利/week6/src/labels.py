# -*- coding: utf-8 -*-
"""
labels.py —— 15 类新闻标签口径

【为什么单独成文件】
    同一份数据会被不同脚本读取（训练、对比、画图、后续服务化）。
    类别名只写一处，任何脚本改标签口径都不用改第二遍。
    顺序必须与 train.json / val.json 里的 label 整数严格一一对应——
    错一位，整张 per-class F1 表就全错位，而且不会报错。

【关于这份数据】
    TNEWS 15 类短文本新闻标题/问句，训练集 53,360 条、验证集 10,000 条，
    最不均衡的两类（证券 257 条 vs 科技 5,955 条）相差 23 倍。
    类别不平衡是这份数据上「Accuracy 好看、Macro-F1 难看」的直接原因，
    所以两个基座都必须用同一套类别加权，否则比较的就不是基座差异了。
"""

LABELS = [
    "故事", "文化", "娱乐", "体育", "财经",
    "房产", "汽车", "教育", "科技", "军事",
    "旅游", "国际", "证券", "农业", "电竞",
]

LABEL2ID = {name: i for i, name in enumerate(LABELS)}
NUM_LABELS = len(LABELS)

# 投研口径的 4 组主题（本作业只用 15 类做对比，这里保留是为了和第六周其他脚本对齐）
GROUP_MAP = {
    "财经": "金融", "证券": "金融", "房产": "金融",
    "科技": "产业", "汽车": "产业", "农业": "产业",
    "国际": "宏观", "军事": "宏观",
    "教育": "噪音", "娱乐": "噪音", "体育": "噪音",
    "电竞": "噪音", "文化": "噪音", "故事": "噪音", "旅游": "噪音",
}


def id2name(label_id: int) -> str:
    """越界时返回 类别N，避免画图阶段因为一条脏标签整张图崩掉"""
    return LABELS[label_id] if 0 <= label_id < NUM_LABELS else f"类别{label_id}"
